#include <stdio.h>
#include <string.h>
#include "cpu.h"
#include "alu.h"
static int fails=0;
static uint16_t TCS=0x100;
static void run(uint8_t *p,int n){
    memset(MEM,0,0x20000);
    memcpy(MEM+((TCS<<4)+0x100),p,n);
    cpu_reset(); cpu.sr[CS]=TCS; cpu.sr[DS]=TCS; cpu.sr[ES]=TCS; cpu.sr[SS]=TCS;
    cpu.r[SP]=0xFFF0; cpu.ip=0x100; cpu.phys=(TCS<<4)+0x100;
    cpu_run(500);
}
static void chk(const char*l,unsigned got,unsigned want){
    if(got!=want){printf("FAIL %-30s got=%04X want=%04X\n",l,got,want);fails++;}
    else printf("ok   %-30s %04X\n",l,got);
}
int main(void){
    run((uint8_t[]){0xB8,0xFF,0x0F,0x05,0x01,0x00,0xF4},7);
    chk("add ax,1 0FFF->1000",cpu.r[AX],0x1000);
    chk("  AF",cpu.flags&F_AF,0x10);
    chk("  CF clear",(cpu.flags&F_CF)?1:0,0);

    run((uint8_t[]){0xB8,0xFF,0xFF,0x05,0x01,0x00,0xF4},7);
    chk("add ax,1 FFFF->0",cpu.r[AX],0);
    chk("  CF",(cpu.flags&F_CF)?1:0,1);
    chk("  ZF",(cpu.flags&F_ZF)?1:0,1);

    run((uint8_t[]){0x04,0x80,0xF4},3);
    cpu.r[AX]=0x0080;
    run((uint8_t[]){0xB0,0x80,0x04,0x80,0xF4},5);
    chk("add al,80h 80+80",cpu.r[AX]&0xFF,0x00);
    chk("  CF",(cpu.flags&F_CF)?1:0,1);
    chk("  OF",(cpu.flags&F_OF)?1:0,1);

    run((uint8_t[]){0xB8,0x05,0x00,0x2D,0x07,0x00,0xF4},7);
    chk("sub ax,7",cpu.r[AX],0xFFFE);
    chk("  CF",(cpu.flags&F_CF)?1:0,1);
    chk("  SF",(cpu.flags&F_SF)?1:0,1);

    run((uint8_t[]){0xB8,0x34,0x12,0x50,0x58,0xF4},6);
    chk("push/pop ax",cpu.r[AX],0x1234);
    chk("  sp",cpu.r[SP],0xFFF0);

    /* call: E8 disp; target = ip_after + disp ; want 0104 => disp = 0 */
    run((uint8_t[]){0xE8,0x00,0x00,0xB8,0x77,0x00,0xF4},7);
    chk("call near self+0 -> mov ax,77",cpu.r[AX],0x0077);
    chk("  sp after ret-less push",cpu.r[SP],0xFFEE);

    run((uint8_t[]){0xE8,0x01,0x00,0xF4,0xB8,0x77,0x00,0xC3,0xF4},9);
    chk("call +2 then ret",cpu.r[AX],0x0077);

    /* loop: disp=-3 from ip_after */
    run((uint8_t[]){0xB9,0x05,0x00,0x31,0xC0,0x40,0xE2,0xFD,0xF4},9);
    chk("loop 5x inc ax",cpu.r[AX],5);

    run((uint8_t[]){0xB8,0x0A,0x00,0xBB,0x0B,0x00,0xF7,0xE3,0xF4},9);
    chk("mul bx 10*11",cpu.r[AX],110);
    run((uint8_t[]){0xB8,0x64,0x00,0x31,0xD2,0xBB,0x07,0x00,0xF7,0xF3,0xF4},11);
    chk("div bx quot",cpu.r[AX],14);
    chk("div bx rem",cpu.r[DX],2);

    run((uint8_t[]){0xB8,0x01,0x00,0xD1,0xE0,0xD1,0xE0,0xF4},8);
    chk("shl ax,1 twice",cpu.r[AX],4);
    run((uint8_t[]){0xB8,0x01,0x80,0xD1,0xF8,0xF4},6);
    chk("sar ax,1 (8001h)",cpu.r[AX],0xC000);
    run((uint8_t[]){0xB8,0x81,0x00,0xD1,0xE8,0xF4},6);
    chk("shr ax,1 (81h)",cpu.r[AX],0x40);

    run((uint8_t[]){0xB8,0xFC,0x00,0xF7,0xD8,0xF4},6);
    chk("neg ax (0xFC)",cpu.r[AX],0xFF04);
    chk("  CF",(cpu.flags&F_CF)?1:0,1);
    run((uint8_t[]){0xB0,0x80,0x98,0xF4},4);
    chk("cbw from AL=80h",cpu.r[AX],0xFF80);

    /* memory store/load round trip */
    run((uint8_t[]){0xB8,0x00,0x02,0x8E,0xD8,0xC7,0x06,0x00,0x14,0x2A,0x00,
                    0xA1,0x00,0x14,0xF4},15);
    chk("store/load [1400h]",cpu.r[AX],0x002A);
    chk("  ds",cpu.sr[DS],0x0200);

    /* conditional jumps */
    run((uint8_t[]){0xB8,0x01,0x00,0x3D,0x01,0x00,0x74,0x01,0xF4,0xB8,0x99,0x00,0xF4},13);
    chk("je taken -> ax=99",cpu.r[AX],0x0099);
    run((uint8_t[]){0xB8,0x02,0x00,0x3D,0x01,0x00,0x74,0x01,0xF4,0xB8,0x99,0x00,0xF4},13);
    chk("je not taken -> ax=2",cpu.r[AX],2);

    /* rep movsb */
    run((uint8_t[]){0xBE,0x00,0x20,0xBF,0x00,0x30,0xB9,0x04,0x00,0xFC,0xF3,0xA4,0xF4},13);
    { int ok=1,i; for(i=0;i<4;i++) if(peek8(0x3000+i)!=peek8(0x2000+i)) ok=0;
      chk("rep movsb 4 bytes",ok,1);
      chk("  si",cpu.r[SI],0x2004);
      chk("  di",cpu.r[DI],0x3004); }

    /* rep stosw */
    run((uint8_t[]){0xB8,0xCD,0xAB,0xBF,0x00,0x30,0xB9,0x03,0x00,0xFC,0xF3,0xAB,0xF4},13);
    chk("rep stosw word0",peek16(0x4000),0xABCD);
    chk("rep stosw word2",peek16(0x4004),0xABCD);

    printf("\n%s (%d failures)\n",fails?"FAILURES":"ALL PASS",fails);
    return fails!=0;
}
